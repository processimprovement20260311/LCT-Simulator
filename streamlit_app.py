def league_tiebreak(tied_teams, schedule, game_results, tiebreak_rng):
    tied = set(tied_teams)
    h2h_pts = {t: 0 for t in tied}
    h2h_pd  = {t: 0 for t in tied}
    h2h_away_pts = {t: 0 for t in tied}
    for r in game_results:
        if r.get("competition") != "league": continue
        h, a = r["home_team"], r["away_team"]
        if h in tied and a in tied and h != a:
            hs, as_ = r["home_score"], r["away_score"]
            h2h_pd[h] += hs - as_; h2h_pd[a] += as_ - hs
            h2h_away_pts[a] += as_
            if hs > as_: h2h_pts[h] += 3
            elif as_ > hs: h2h_pts[a] += 3
            else: h2h_pts[h] += 1; h2h_pts[a] += 1
    overall_pd = {t: 0 for t in tied}
    for r in game_results:
        if r.get("competition") != "league": continue
        h, a = r["home_team"], r["away_team"]
        if h in tied and a in tied:
            overall_pd[h] += r["home_score"] - r["away_score"]
            overall_pd[a] += r["away_score"] - r["home_score"]
    def partition(teams, key_fn):
        buckets = {}
        for t in teams: buckets.setdefault(key_fn(t), []).append(t)
        return [buckets[k] for k in sorted(buckets.keys(), reverse=True)]
    working = [list(tied)]
    for key_fn in [lambda t: h2h_pts[t], lambda t: overall_pd[t],
                   lambda t: h2h_pd[t], lambda t: h2h_away_pts[t]]:
        nxt = []
        for grp in working:
            if len(grp) <= 1: nxt.append(grp)
            else: nxt.extend(partition(grp, key_fn))
        working = nxt
    final = []
    for grp in working:
        if len(grp) > 1: substream_shuffle(grp, tiebreak_rng)
        final.extend(grp)
    return final

def compute_league_table(schedule, game_results, tiebreak_rng=None):
    if tiebreak_rng is None: tiebreak_rng = Xoshiro(0)
    table = {t: {"pts":0,"gd":0,"gf":0,"w":0,"d":0,"l":0} for t in TEAMS}
    for r in game_results:
        if r.get("competition") != "league": continue
        h, a = r["home_team"], r["away_team"]
        table[h]["gf"] += r["home_score"]; table[h]["gd"] += r["home_score"] - r["away_score"]
        table[a]["gf"] += r["away_score"]; table[a]["gd"] += r["away_score"] - r["home_score"]
        if r["home_score"] > r["away_score"]:
            table[h]["pts"] += 3; table[h]["w"] += 1; table[a]["l"] += 1
        elif r["away_score"] > r["home_score"]:
            table[a]["pts"] += 3; table[a]["w"] += 1; table[h]["l"] += 1
        else:
            table[h]["pts"] += 1; table[h]["d"] += 1
            table[a]["pts"] += 1; table[a]["d"] += 1
    by_pts = {}
    for t in TEAMS: by_pts.setdefault(table[t]["pts"], []).append(t)
    ranked = []
    for pts in sorted(by_pts.keys(), reverse=True):
        grp = by_pts[pts]
        if len(grp) == 1: ranked.extend(grp)
        else: ranked.extend(league_tiebreak(grp, schedule, game_results, tiebreak_rng))
    return ranked, table

def resolve_soe_tie(t1, t2, r1, r2, subs, leg2_date):
    a1 = r1["home_score"] + r2["away_score"]
    a2 = r1["away_score"] + r2["home_score"]
    if a1 > a2: return t1, False, None
    if a2 > a1: return t2, False, None
    t1_away = r2["away_score"]; t2_away = r1["away_score"]
    if t1_away > t2_away: return t1, False, None
    if t2_away > t1_away: return t2, False, None
    r2_ot = sim_game(t2, t1, "home", True, subs, "soe_r32",
                     "L2-OT", leg2_date, BASE_RATINGS, 0,
                     forced_weather=forced_weather_setting())
    return r2_ot["winner"], True, r2_ot

